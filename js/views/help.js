export function renderHelp(app) {
  app.innerHTML = `
    <div class="help-page">
      <p class="help-intro">دليل مختصر لاستخدام مِحوَر. اختر قسماً أو افتح الجولة التعريفية.</p>
      <p><button class="button button-secondary" type="button" id="replay-tour">إعادة الجولة التعريفية</button></p>
      <nav class="help-toc" aria-label="أقسام الدليل">
        ${SECTIONS.map((section) => `<a href="#/help" data-help-target="${section.id}">${section.title}</a>`).join("")}
      </nav>
      ${SECTIONS.map((section) => `
        <details class="help-section" id="help-${section.id}" open>
          <summary>${section.title}</summary>
          ${section.body.map((paragraph) => `<p>${paragraph}</p>`).join("")}
        </details>`).join("")}
    </div>`;
  app.querySelector("#replay-tour").addEventListener("click", () => {
    document.querySelector("#onboarding-dialog")?.showModal();
  });
  app.querySelectorAll("[data-help-target]").forEach((link) => link.addEventListener("click", (event) => {
    event.preventDefault();
    document.getElementById(`help-${link.dataset.helpTarget}`)?.scrollIntoView({ behavior: "smooth", block: "start" });
  }));
}
